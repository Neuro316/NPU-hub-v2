#!/usr/bin/env node
// scripts/health/gen-repo-facts.cjs
// Hub Health (q23) reads two facts about the repo that a serverless build cannot see at run time, so they are written
// into src/lib/health/generated/repo-facts.ts when the code changes:
//   hubMigrations   the names of supabase/migrations/*.sql (the migration parity tile filters to the Hub band)
//   guards          each guard's result line (ok, new, known) from scripts/guards/run-guards.cjs
//   prefixOverlap   numbers used by both a hub_NNN file and a pf_NNN platform migration (the G5 tile shows the known
//                   pf_211 to pf_213 collision as amber)
// `--check` exits 1 when the generated file is stale; scripts/verify.cjs runs it.
const fs = require('fs'), path = require('path'), { spawnSync } = require('child_process')

const ROOT = path.resolve(__dirname, '..', '..')
const OUT = path.join(ROOT, 'src', 'lib', 'health', 'generated', 'repo-facts.ts')

const files = fs.readdirSync(path.join(ROOT, 'supabase', 'migrations')).filter((f) => f.endsWith('.sql')).map((f) => f.replace(/\.sql$/, '')).sort()

const g = spawnSync(process.execPath, [path.join(ROOT, 'scripts', 'guards', 'run-guards.cjs')], { cwd: ROOT, encoding: 'utf8', env: { ...process.env, TAMPER: '' } })
const guards = []
for (const line of String(g.stdout || '').split('\n')) {
  const m = /^(ok|FAIL)\s+(G\d+):\s+(\d+) new, (\d+) known/.exec(line.trim())
  if (m) guards.push({ id: m[2], ok: m[1] === 'ok', new: Number(m[3]), known: Number(m[4]) })
}

const pf = fs.readFileSync(path.join(ROOT, 'scripts', 'guards', 'platform-migrations.txt'), 'utf8').split('\n')
  .map((l) => /^pf_(\d{3})_/.exec(l.trim())?.[1]).filter(Boolean)
const hubNums = new Set(files.map((f) => /^hub_(\d{3})_/.exec(f)?.[1]).filter(Boolean))
const prefixOverlap = Array.from(new Set(pf.filter((n) => hubNums.has(n)))).sort()

const body = `// GENERATED by scripts/health/gen-repo-facts.cjs. Do not edit; run \`node scripts/health/gen-repo-facts.cjs\`.
import type { RepoFacts } from '../run'

export const REPO_FACTS: RepoFacts = ${JSON.stringify({ hubMigrations: files, guards, prefixOverlap }, null, 2).replace(/"([a-zA-Z]+)":/g, '$1:').replace(/"/g, "'")}
`
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (cur !== body) { console.error('src/lib/health/generated/repo-facts.ts is stale: run node scripts/health/gen-repo-facts.cjs'); process.exit(1) }
  console.log('repo-facts current')
  process.exit(0)
}
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, body)
console.log(`wrote ${path.relative(ROOT, OUT)}: ${files.length} migrations, ${guards.length} guards, overlap ${prefixOverlap.length}`)
